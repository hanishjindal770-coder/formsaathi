// Generates out/sw.js after `next build`. The service worker precaches the app shell (all
// hashed JS/CSS, fonts, icons and the home + generic tool pages in both languages) so every
// tool works offline after the first visit. Exam pages are cached as they are visited.
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";

const OUT = "out";
// Sub-path on GitHub Pages ("/formsaathi"); empty on a custom domain. Must match next.config.
const BASE = (process.env.NEXT_PUBLIC_BASE_PATH || "").replace(/\/$/, "");
if (!fs.existsSync(OUT)) throw new Error("out/ not found: run next build first");

function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((d) => {
    const p = path.join(dir, d.name);
    return d.isDirectory() ? walk(p) : [p];
  });
}
const rel = (file) => "/" + path.relative(OUT, file).split(path.sep).join("/");

const assets = [
  // Big chunks (pdf.js) are left out of the install download; they are cached the first time a PDF tool uses them.
  ...walk(path.join(OUT, "_next", "static")).filter((f) => !f.endsWith(".map") && fs.statSync(f).size < 250 * 1024).map(rel),
  ...["/icons/icon-192.png", "/icons/icon.svg", "/manifest.webmanifest"],
];
// Home + every generic tool page. Exam pages are cached on first visit.
const TOOL_PAGES = ["photo-resize", "signature-resize", "thumb-resize", "declaration-resize", "age-calculator", "pdf-compress", "image-to-pdf", "pdf-merge", "passport-photo-sheet", "image-convert"];
const pages = ["hi", "en"].flatMap((l) => [`/${l}/`, ...TOOL_PAGES.map((t) => `/${l}/${t}/`)]);
for (const p of pages) if (!fs.existsSync(path.join(OUT, p, "index.html"))) throw new Error(`missing page ${p}`);

const precache = [...pages, ...assets].map((u) => BASE + u);
const version = crypto.createHash("sha256").update(precache.join("\n")).digest("hex").slice(0, 10);
const bytes = assets.reduce((n, u) => n + fs.statSync(path.join(OUT, u)).size, 0);

const sw = `/* FormSaathi service worker, generated by scripts/build-sw.mjs. Version ${version}. */
const VERSION = ${JSON.stringify(version)};
const SHELL = "shell-" + VERSION;
const RUNTIME = "runtime-v1";
const PRECACHE = ${JSON.stringify(precache)};
const BASE = ${JSON.stringify(BASE)};

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(SHELL).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith("shell-") && k !== SHELL).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

// Next.js adds ?_rsc=<hash> to navigation payload requests; the hash doesn't change the content.
function cacheKey(request) {
  const u = new URL(request.url);
  u.searchParams.delete("_rsc");
  return u.toString();
}

async function trimRuntime(max = 200) {
  const cache = await caches.open(RUNTIME);
  const keys = await cache.keys();
  for (let i = 0; i < keys.length - max; i++) await cache.delete(keys[i]);
}

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;

  // Hashed build assets, fonts, icons: cache first, they never change under the same URL.
  if (url.pathname.startsWith(BASE + "/_next/static/") || url.pathname.startsWith(BASE + "/icons/")) {
    event.respondWith(
      caches.match(req).then((hit) => hit || fetch(req).then((res) => {
        if (res.ok) { const copy = res.clone(); caches.open(RUNTIME).then((c) => c.put(req, copy)); }
        return res;
      })),
    );
    return;
  }

  // Pages and RSC payloads: network first (fresh exam rules), cache as fallback when offline.
  const key = cacheKey(req);
  event.respondWith(
    fetch(req)
      .then((res) => {
        if (res.ok) {
          const copy = res.clone();
          caches.open(RUNTIME).then((c) => c.put(key, copy)).then(() => trimRuntime());
        }
        return res;
      })
      .catch(async () => {
        const hit = (await caches.match(key)) || (await caches.match(req, { ignoreSearch: true }));
        if (hit) return hit;
        if (req.mode === "navigate") {
          const lang = url.pathname.startsWith(BASE + "/en") ? "en" : "hi";
          return (await caches.match(BASE + "/" + lang + "/")) || Response.error();
        }
        return Response.error();
      }),
  );
});
`;
fs.writeFileSync(path.join(OUT, "sw.js"), sw);
console.log(`✓ sw.js: ${precache.length} files precached (${Math.round(bytes / 1024)} KB of assets), version ${version}`);
